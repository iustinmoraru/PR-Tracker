package com.iustinmoraru.prtracker.ui.auth

import android.annotation.SuppressLint
import android.app.Activity
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.ClearCredentialException
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenParsingException
import com.iustinmoraru.prtracker.data.auth.AuthError

/**
 * Shows the "Sign in with Google" bottom sheet through Android's Credential Manager and
 * returns the Google ID token. It needs an [Activity] to display the system UI, which is why
 * it lives in the UI layer; the token is then passed to the view model.
 */
class GoogleSignInHelper(private val activity: Activity) {

    private val credentialManager = CredentialManager.create(activity)

    /** Result of a Google sign-in attempt: either an ID token or an [AuthError]. */
    sealed interface Outcome {
        data class Token(val idToken: String) : Outcome
        data class Error(val error: AuthError) : Outcome
    }

    suspend fun requestIdToken(): Outcome {
        val clientId = webClientId() ?: return Outcome.Error(AuthError.NOT_CONFIGURED)
        val googleOption = GetSignInWithGoogleOption.Builder(clientId).build()
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(googleOption)
            .build()

        return try {
            val credential = credentialManager.getCredential(activity, request).credential
            if (credential is CustomCredential &&
                credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
            ) {
                Outcome.Token(GoogleIdTokenCredential.createFrom(credential.data).idToken)
            } else {
                Outcome.Error(AuthError.GOOGLE_FAILED)
            }
        } catch (e: GetCredentialCancellationException) {
            Outcome.Error(AuthError.GOOGLE_CANCELLED)
        } catch (e: NoCredentialException) {
            Outcome.Error(AuthError.GOOGLE_NO_ACCOUNT)
        } catch (e: GetCredentialException) {
            Outcome.Error(AuthError.GOOGLE_FAILED)
        } catch (e: GoogleIdTokenParsingException) {
            Outcome.Error(AuthError.GOOGLE_FAILED)
        }
    }

    /** Forgets the chosen Google account so the picker appears again after logout. */
    suspend fun clearCredentials() {
        try {
            credentialManager.clearCredentialState(ClearCredentialStateRequest())
        } catch (_: ClearCredentialException) {
            // Nothing to clear or provider unavailable: safe to ignore on logout.
        }
    }

    /**
     * The OAuth web client ID is generated by the Google Services plugin from
     * google-services.json. It is looked up by name so the app still compiles without it.
     */
    @SuppressLint("DiscouragedApi")
    private fun webClientId(): String? {
        val id = activity.resources.getIdentifier("default_web_client_id", "string", activity.packageName)
        return if (id != 0) activity.getString(id) else null
    }
}
